"""
heatmap_significant_features.py
================================
Creates the "Significant Features Across Fractions" heatmap.

Requirements: numpy, pandas, matplotlib, seaborn, scipy

Run in Colab:
    !python heatmap_significant_features.py
Or paste directly into a Colab cell.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import os
from scipy.stats import ttest_rel

# ── CONFIG ────────────────────────────────────────────────────────────────────
# Base directory containing fraction subfolders
# Each subfolder must contain X_central.npy, X_peripheral.npy, case_ids.npy
AGGREGATED_BASE = "/content/drive/MyDrive/intra_tumor_heterogen_589/"
FRACTIONS       = [0.4, 0.5, 0.6]
SAVE_PATH       = "/content/drive/MyDrive/intra_tumor_heterogen_589/heatmap_sign_all_fractions.png"
# ─────────────────────────────────────────────────────────────────────────────

# ── Feature names ─────────────────────────────────────────────────────────────
HARALICK_BASE = [
    "AngularSecondMoment", "Contrast", "Correlation",
    "SumOfSquaresVariance", "SumAverage", "SumVariance", "SumEntropy",
    "Entropy", "DifferenceVariance", "DifferenceEntropy",
    "InfoMeasureCorr1", "InfoMeasureCorr2", "MaximalCorrelationCoeff",
]
FEATURE_NAMES = (
    [f"{f}_Primary"   for f in HARALICK_BASE] +
    [f"{f}_Secondary" for f in HARALICK_BASE]
)

# ── Run paired t-test per feature per fraction ────────────────────────────────
significance = {}   # fraction → array of 0/1 per feature

for fraction in FRACTIONS:
    frac_dir   = os.path.join(AGGREGATED_BASE, f"aggregated_{fraction}")
    central    = np.load(os.path.join(frac_dir, "central_vectors.npy"))
    peripheral = np.load(os.path.join(frac_dir, "peripheral_vectors.npy"))

    # Drop CT channel if present
    if central.shape[1] == 27:
        central    = central[:, 1:]
        peripheral = peripheral[:, 1:]

    assert central.shape[1] == 26

    n_feat = central.shape[1]
    sig    = np.zeros(n_feat, dtype=int)

    for i in range(n_feat):
        c = central[:, i];    p = peripheral[:, i]
        valid = np.isfinite(c) & np.isfinite(p)
        _, pv = ttest_rel(c[valid], p[valid])
        # Bonferroni correction
        if pv * n_feat < 0.05:
            sig[i] = 1

    significance[fraction] = sig
    n_sig = sig.sum()
    print(f"Fraction {fraction}: {n_sig}/26 significant features")

# ── Build DataFrame ───────────────────────────────────────────────────────────
df = pd.DataFrame(
    {fraction: significance[fraction] for fraction in FRACTIONS},
    index=FEATURE_NAMES
)

# 1. Υπολογισμός σκορ σταθερότητας
df["_stability"] = df.sum(axis=1)

# 2. Ταξινόμηση: Πρώτα κατά '_stability' (φθίνουσα) και μετά κατά το Index (αύξουσα)
df = df.sort_values(by="_stability", ascending=False).sort_index(kind="mergesort")

# 3. Αφαίρεση της βοηθητικής στήλης
df = df.drop(columns=["_stability"])



print(f"\nFeatures significant across ALL fractions: {(df.sum(axis=1)==3).sum()}")
print(f"Features significant across 2 fractions : {(df.sum(axis=1)==2).sum()}")
print(f"Features significant across 1 fraction  : {(df.sum(axis=1)==1).sum()}")
print(f"Features not significant in any          : {(df.sum(axis=1)==0).sum()}")

# ── Plot ──────────────────────────────────────────────────────────────────────
n_features = len(df)
fig_height = max(8, n_features * 0.42 + 2)

