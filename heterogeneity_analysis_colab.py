def analyse_magnitude(heterog, out_dir):
    """L2 norm of the heterogeneity vector per case."""
    magnitudes = np.linalg.norm(heterog, axis=1)
    stats = {
        'n_cases': len(magnitudes),
        'mean':    magnitudes.mean(),
        'std':     magnitudes.std(ddof=1),
        'median':  float(np.median(magnitudes)),
        'q25':     float(np.percentile(magnitudes, 25)),
        'q75':     float(np.percentile(magnitudes, 75)),
        'min':     float(magnitudes.min()),
        'max':     float(magnitudes.max()),
    }
    print(f'  Mean magnitude: {stats["mean"]:.4f} ± {stats["std"]:.4f}')
    pd.DataFrame([stats]).to_csv(
        os.path.join(out_dir, 'magnitude_stats.csv'), index=False)

    fig, axes = plt.subplots(1, 2, figsize=(13, 5))
    axes[0].hist(magnitudes, bins=30, color='mediumpurple',
                 edgecolor='white', alpha=0.85)
    axes[0].axvline(magnitudes.mean(), color='tomato', linestyle='--',
                    linewidth=1.8, label=f'Mean={magnitudes.mean():.3f}')
    axes[0].axvline(float(np.median(magnitudes)), color='navy', linestyle=':',
                    linewidth=1.8, label=f'Median={float(np.median(magnitudes)):.3f}')
    axes[0].set_xlabel('Heterogeneity Magnitude (L2 norm)')
    axes[0].set_ylabel('Count')
    axes[0].set_title('Distribution of Intra-Tumor Heterogeneity')
    axes[0].legend(fontsize=9)

    sorted_mag = np.sort(magnitudes)
    axes[1].plot(sorted_mag, color='mediumpurple', linewidth=1.5)
    axes[1].fill_between(range(len(sorted_mag)), sorted_mag,
                         alpha=0.2, color='mediumpurple')
    axes[1].set_xlabel('Case rank (sorted)')
    axes[1].set_ylabel('Heterogeneity Magnitude')
    axes[1].set_title('Sorted Magnitudes — each point = one PDAC case')

    plt.suptitle('Intra-Tumor Heterogeneity Magnitude', fontsize=12, fontweight='bold')
    plt.tight_layout()
    save_fig(fig, os.path.join(out_dir, 'plots', '03_magnitude.png'))
    return magnitudes


def run_pca(heterog, out_dir):
    """PCA on the heterogeneity vectors."""
    scaler   = StandardScaler()
    H_scaled = scaler.fit_transform(heterog)
    n_comp   = min(10, H_scaled.shape[1])
    pca      = PCA(n_components=n_comp)
    coords   = pca.fit_transform(H_scaled)
    explained  = pca.explained_variance_ratio_
    cumulative = np.cumsum(explained)

    print(f'  PC1={explained[0]*100:.1f}%  PC1+PC2={cumulative[1]*100:.1f}%  '
          f'n_for_80%={int(np.searchsorted(cumulative, 0.80))+1}')

    pd.DataFrame(pca.components_.T,
                 index=FEATURE_NAMES,
                 columns=[f'PC{i+1}' for i in range(n_comp)]
                 ).to_csv(os.path.join(out_dir, 'pca_loadings.csv'))

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    axes[0].bar(range(1, len(explained)+1), explained*100,
                color='steelblue', alpha=0.8, label='Individual')
    axes[0].step(range(1, len(cumulative)+1), cumulative*100,
                 color='tomato', linewidth=2, label='Cumulative')
    axes[0].axhline(80, color='gray', linestyle='--', linewidth=1,
                    alpha=0.7, label='80% threshold')
    axes[0].set_xlabel('Principal Component')
    axes[0].set_ylabel('Explained Variance (%)')
    axes[0].set_title('PCA Scree Plot')
    axes[0].legend(fontsize=9)
    axes[0].set_xticks(range(1, len(explained)+1))

    axes[1].scatter(coords[:, 0], coords[:, 1],
                    alpha=0.45, s=18, color='mediumpurple', edgecolors='none')
    axes[1].set_xlabel(f'PC1 ({explained[0]*100:.1f}%)')
    axes[1].set_ylabel(f'PC2 ({explained[1]*100:.1f}%)')
    axes[1].set_title('Heterogeneity PCA Space\n(each point = one PDAC tumor)')

    plt.suptitle('PCA of Intra-Tumor Heterogeneity Vectors', fontsize=12, fontweight='bold')
    plt.tight_layout()
    save_fig(fig, os.path.join(out_dir, 'plots', '04_pca.png'))
    return pca, coords, H_scaled


def run_kmeans(H_scaled, coords, out_dir, k_range=(2, 6)):
    """K-means clustering on the standardised heterogeneity vectors.
    Tests k=2..6, picks the best k by silhouette score."""
    print('  K-means clustering...')
    sil_scores = {}
    for k in range(k_range[0], k_range[1]+1):
        km     = KMeans(n_clusters=k, random_state=42, n_init=10)
        labels = km.fit_predict(H_scaled)
        sil    = silhouette_score(H_scaled, labels)
        sil_scores[k] = sil
        print(f'    k={k}  silhouette={sil:.4f}')

    best_k = max(sil_scores, key=sil_scores.get)
    print(f'  Best k={best_k} (silhouette={sil_scores[best_k]:.4f})')

    km_best = KMeans(n_clusters=best_k, random_state=42, n_init=10)
    best_labels = km_best.fit_predict(H_scaled)

    pd.DataFrame({'sil_scores': sil_scores}).to_csv(
        os.path.join(out_dir, 'kmeans_silhouette.csv'))

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    axes[0].plot(list(sil_scores.keys()), list(sil_scores.values()),
                 'o-', color='steelblue', linewidth=2, markersize=7)
    axes[0].axvline(best_k, color='tomato', linestyle='--',
                    linewidth=1.5, label=f'Best k={best_k}')
    axes[0].set_xlabel('Number of clusters (k)')
    axes[0].set_ylabel('Silhouette score')
    axes[0].set_title('K-Means: Silhouette Scores')
    axes[0].legend(fontsize=9)
    axes[0].set_xticks(list(sil_scores.keys()))

    palette = plt.cm.tab10.colors
    for k_idx in range(best_k):
        mask = best_labels == k_idx
        axes[1].scatter(coords[mask, 0], coords[mask, 1],
                        alpha=0.55, s=20, color=palette[k_idx],
                        label=f'Cluster {k_idx+1} (n={mask.sum()})',
                        edgecolors='none')
    axes[1].set_xlabel(f'PC1')
    axes[1].set_ylabel(f'PC2')
    axes[1].set_title(f'K-Means Clusters (k={best_k}) in PCA Space')
    axes[1].legend(fontsize=8, markerscale=1.5)

    plt.suptitle(f'K-Means Heterogeneity Clustering (best k={best_k})',
                 fontsize=12, fontweight='bold')
    plt.tight_layout()
    save_fig(fig, os.path.join(out_dir, 'plots', '05_kmeans.png'))
    return best_labels, best_k


def volume_correlation(magnitudes, volumes, out_dir):
    """Pearson + Spearman correlation between heterogeneity magnitude and tumor volume."""
    r_p, p_p = pearsonr(magnitudes,  volumes)
    r_s, p_s = spearmanr(magnitudes, volumes)
    print(f'  Pearson  r={r_p:.3f} p={p_p:.4f}')
    print(f'  Spearman r={r_s:.3f} p={p_s:.4f}')

    pd.DataFrame({
        'metric':   ['Pearson', 'Spearman'],
        'r':        [r_p, r_s],
        'p_value':  [p_p, p_s],
        'n_cases':  [len(magnitudes), len(magnitudes)],
    }).to_csv(os.path.join(out_dir, 'volume_correlation.csv'), index=False)

    vols_cm3 = volumes / 1000
    m, b     = np.polyfit(vols_cm3, magnitudes, 1)
    x_line   = np.linspace(vols_cm3.min(), vols_cm3.max(), 200)

    fig, ax = plt.subplots(figsize=(7, 6))
    ax.scatter(vols_cm3, magnitudes, alpha=0.45, s=18,
               color='steelblue', edgecolors='none')
    ax.plot(x_line, m*x_line+b, color='tomato', linewidth=2,
            label=f'Pearson r={r_p:.3f}, p={p_p:.3f}\n'
                  f'Spearman r={r_s:.3f}, p={p_s:.3f}')
    ax.set_xlabel('Tumor Volume (cm³)')
    ax.set_ylabel('Heterogeneity Magnitude (L2 norm)')
    ax.set_title('Intra-Tumor Heterogeneity vs. Tumor Size\n(PDAC cases)')
    ax.legend(fontsize=9)
    plt.tight_layout()
    save_fig(fig, os.path.join(out_dir, 'plots', '06_volume_correlation.png'))


def plot_heatmap(central, peripheral, out_dir):
    """Mean central / peripheral / difference heatmap."""
    df_heat = pd.DataFrame({
        'Central':    central.mean(axis=0),
        'Peripheral': peripheral.mean(axis=0),
        'Difference': central.mean(axis=0) - peripheral.mean(axis=0),
    }, index=FEATURE_NAMES)

    fig, axes = plt.subplots(1, 3, figsize=(16, 10))
    for ax, col, title, cmap in zip(
        axes,
        ['Central', 'Peripheral', 'Difference'],
        ['Mean Central', 'Mean Peripheral', 'Difference (C−P)'],
        ['Blues', 'Oranges', 'coolwarm']
    ):
        sns.heatmap(df_heat[[col]], ax=ax, cmap=cmap,
                    center=0 if col=='Difference' else None,
                    yticklabels=FEATURE_NAMES, xticklabels=[col],
                    annot=True, fmt='.3f', annot_kws={'size': 7},
                    cbar_kws={'shrink': 0.6})
        ax.set_title(title, fontsize=11, fontweight='bold')
        ax.tick_params(axis='y', labelsize=7)

    plt.suptitle('Mean CoLIAGe Features: Central vs. Peripheral (PDAC cohort)',
                 fontsize=13, fontweight='bold')
    plt.tight_layout()
    save_fig(fig, os.path.join(out_dir, 'plots', '07_heatmap.png'))

