def apply_bonferroni(p_values, n_tests=None):
    n = n_tests or len(p_values)
    return np.clip(np.array(p_values) * n, 0, 1)

def cohens_d_paired(a, b):
    diff = a - b
    return diff.mean() / (diff.std(ddof=1) + 1e-12)

