def load_fraction_data(fraction):
    """Load aggregated arrays for a given fraction. Drops CT channel if present."""
    frac_str = f'fraction_{fraction}'
    # The AGGREGATED_BASE is already set to the specific fraction's aggregated data folder.
    # So, we should use AGGREGATED_BASE directly, not join an additional frac_str subfolder.
    frac_dir = AGGREGATED_BASE

    # Support both naming conventions
    def try_load(names):
        for name in names:
            p = os.path.join(frac_dir, name)
            if os.path.exists(p):
                return np.load(p)
        raise FileNotFoundError(f'None of {names} found in {frac_dir}')

    central    = try_load(['X_central.npy',      'central_vectors.npy'])
    peripheral = try_load(['X_peripheral.npy',   'peripheral_vectors.npy'])
    heterog    = try_load(['X_hetero.npy','heterogeneity_vectors.npy'])
    case_ids   = np.load(os.path.join(frac_dir, 'case_ids.npy'), allow_pickle=True)

    # Drop CT intensity channel (index 0) if 27 features present
    for arr_name, arr in [('central', central), ('peripheral', peripheral), ('heterogeneity', heterog)]:
        if arr.shape[1] == 27:
            pass  # handled below
    if central.shape[1] == 27:
        central    = central[:, 1:]
        peripheral = peripheral[:, 1:]
        heterog    = heterog[:, 1:]
        print(f'  [{frac_str}] Dropped CT channel — keeping 26 Haralick features.')

    assert central.shape[1] == 26, f'Expected 26 features, got {central.shape[1]}'

    # Optional tumor volumes
    vol_path = os.path.join(frac_dir, f'tumor_volumes_{fraction}.npy')
    volumes  = np.load(vol_path).astype(np.float32) if os.path.exists(vol_path) else None

    print(f'  [{frac_str}] Loaded {len(case_ids)} cases, '
          f'volumes={"yes" if volumes is not None else "no"}')
    return central, peripheral, heterog, case_ids, volumes

