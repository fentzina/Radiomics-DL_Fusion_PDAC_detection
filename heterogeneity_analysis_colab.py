def run_paired_tests(central, peripheral, out_dir):
    """Paired t-test + Wilcoxon per feature with Bonferroni correction."""
    n_feat   = len(FEATURE_NAMES)
    results  = []
    for i, fname in enumerate(FEATURE_NAMES):
        c = central[:, i]
        p = peripheral[:, i]
        valid = np.isfinite(c) & np.isfinite(p)
        c, p  = c[valid], p[valid]
        t_stat, p_t = ttest_rel(c, p)
        try:
            w_stat, p_w = wilcoxon(c - p)
        except ValueError:
            w_stat, p_w = np.nan, np.nan
        results.append({
            'feature': fname, 'n_valid': int(valid.sum()),
            'mean_central': c.mean(), 'mean_peripheral': p.mean(),
            'mean_diff': (c-p).mean(), 'std_diff': (c-p).std(ddof=1),
            'cohens_d': cohens_d_paired(c, p),
            't_stat': t_stat, 'p_ttest_raw': p_t,
            'w_stat': w_stat, 'p_wilcox_raw': p_w,
        })
    df = pd.DataFrame(results)
    df['p_ttest_bonf']  = apply_bonferroni(df['p_ttest_raw'].values,  n_feat)
    df['p_wilcox_bonf'] = apply_bonferroni(df['p_wilcox_raw'].fillna(1).values, n_feat)
    df['sig_ttest']  = df['p_ttest_bonf']  < 0.05
    df['sig_wilcox'] = df['p_wilcox_bonf'] < 0.05
    df = df.sort_values('p_ttest_bonf')

    n_sig = int(df['sig_ttest'].sum())
    print(f'  Significant features (Bonferroni t-test): {n_sig}/{n_feat}')
    df.to_csv(os.path.join(out_dir, 'paired_tests.csv'), index=False)

    # Plot
    fig, ax = plt.subplots(figsize=(14, 8))
    log_p   = -np.log10(df['p_ttest_bonf'].clip(lower=1e-10))
    colors  = ['tomato' if s else 'steelblue' for s in df['sig_ttest']]
    ax.barh(df['feature'], log_p, color=colors, edgecolor='none')
    ax.axvline(-np.log10(0.05), color='black', linestyle='--',
               linewidth=1.2, label='p=0.05 (Bonferroni)')
    ax.set_xlabel('-log₁₀(Bonferroni p-value)', fontsize=11)
    ax.set_title('Central vs. Peripheral — Feature Significance\n'
                 '(red = significant, α=0.05 Bonferroni)', fontsize=12, fontweight='bold')
    ax.tick_params(axis='y', labelsize=8)
    ax.legend(fontsize=9)
    plt.tight_layout()
    save_fig(fig, os.path.join(out_dir, 'plots', '01_significance.png'))
    return df


