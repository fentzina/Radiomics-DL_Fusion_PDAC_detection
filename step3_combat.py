"""# Apply saved ComBat estimates to val and test (transform only — no re-fitting)"""

print("Applying ComBat to val and test (transform only) ...")
def apply_to_split(X_split, sc_split, y_split, mask_split, split_name):
    """
    Apply the fitted combat_model to the ComBat-eligible cases in a split,
    then reconstruct the full array with passthrough cases unchanged.
    """
    if mask_split.sum() == 0:
        print(f"  {split_name}: no ComBat-eligible cases — returned unchanged.")
        return X_split.copy()

    X_cb   = X_split[mask_split]
    sc_cb  = sc_split[mask_split]
    y_cb   = y_split[mask_split]

    covars = pd.DataFrame({
        "SITE": sc_cb,
        "PDAC": y_cb.astype(int),
    })

    X_cb_h = harmonizationApply(X_cb.copy().astype(np.float64),
                                 covars, combat_model)

    X_full_h = reconstruct_full_array(X_split, X_cb_h, mask_split)
    print(f"  {split_name}: harmonized {mask_split.sum()} cases, "
          f"passthrough {(~mask_split).sum()} cases → shape {X_full_h.shape}")
    return X_full_h

