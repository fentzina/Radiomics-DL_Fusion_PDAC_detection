"""# (Partial) ComBat FUNCTIONS"""

def get_combat_mask(scanners: np.ndarray) -> np.ndarray:
    """
    Returns a boolean mask: True for cases that belong to COMBAT_SITES.
    Cases from excluded or unknown sites are False → passthrough.
    """
    return np.array([s in COMBAT_SITES for s in scanners])

def reconstruct_full_array(X_original: np.ndarray,
                            X_harmonized_subset: np.ndarray,
                            combat_mask: np.ndarray) -> np.ndarray:
    """
    Slot the harmonized subset back into a copy of the original array,
    preserving original values for passthrough cases.

    Parameters
    ----------
    X_original         : (N, F)  full array (all cases)
    X_harmonized_subset: (M, F)  ComBat output (M = combat_mask.sum())
    combat_mask        : (N,)    boolean, True where ComBat was applied

    Returns
    -------
    (N, F) array — ComBat cases replaced, passthrough cases unchanged
    """
    X_out = X_original.copy()
    X_out[combat_mask] = X_harmonized_subset
    return X_out

